/**
 * Returns true when the given profile email is allowed to see the Health Risk
 * Score feature. Case-insensitive and whitespace-tolerant. Empty/undefined
 * emails are never allowed.
 */
export function isHealthScoreAllowed(email: string | null | undefined): boolean {
  if (!email) return false
  return HEALTH_SCORE_ALLOWLIST.has(email.trim().toLowerCase())
}
